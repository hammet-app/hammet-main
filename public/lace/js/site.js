/* ---------- Scroll reveal, count-up ---------- */
(function(){
  var els = $$('.reveal');
  function countUp(el){
    var to = +el.getAttribute('data-count'), t0 = null;
    function step(ts){ if (!t0) t0 = ts; var p = Math.min(1, (ts - t0) / 1200); el.textContent = Math.round(to * (1 - Math.pow(1 - p, 3))).toLocaleString('en-US'); if (p < 1) requestAnimationFrame(step); }
    if (reduce) el.textContent = to.toLocaleString('en-US'); else requestAnimationFrame(step);
  }
  if (!('IntersectionObserver' in window)){ els.forEach(function(e){ e.classList.add('in'); }); $$('[data-count]').forEach(countUp); return; }
  var io = new IntersectionObserver(function(entries){
    entries.forEach(function(en){
      if (!en.isIntersecting) return;
      en.target.classList.add('in');
      (function(t){ setTimeout(function(){ t.classList.add('done'); }, 1300); })(en.target);
      $$('[data-count]', en.target).forEach(countUp);
      io.unobserve(en.target);
    });
  }, {threshold:.12, rootMargin:'0px 0px -6% 0px'});
  els.forEach(function(e){ io.observe(e); });
  window.__observeReveal = function(){ $$('.reveal:not(.in)').forEach(function(e){ io.observe(e); }); };
})();

