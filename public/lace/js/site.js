/* ---------- Bootcamp status (Lagos time). Preview any date with ?bcdate=2026-10-22 ---------- */
var BC = {};
function computeBC(forced){
  var q = (forced || (location.href.match(/bcdate=(\d{4}-\d{2}-\d{2})/) || [])[1] || '').split('-');
  var n = q.length === 3 ? new Date(Date.UTC(+q[0], +q[1] - 1, +q[2], 12)) : new Date(Date.now() + 3600000); // Lagos = UTC+1
  var f = C.bootcamp.firstDay.split('-').map(Number);
  var first = Date.UTC(f[0], f[1] - 1, f[2]);
  var today = Date.UTC(n.getUTCFullYear(), n.getUTCMonth(), n.getUTCDate());
  BC.idx = Math.round((today - first) / 86400000) + 1;           // 1 = first day
  BC.total = C.bootcamp.days; BC.first = first;
  BC.state = BC.idx < 1 ? 'before' : (BC.idx > BC.total ? 'done' : 'live');
}
function renderStatus(){
  document.body.setAttribute('data-bcstate', BC.state);
  $$('.bclive-t').forEach(function(t){
    if (BC.state === 'live') t.textContent = 'Live now \u00B7 Day ' + BC.idx + ' of ' + BC.total + ' \u00B7 tonight ' + C.bootcamp.time;
    else if (BC.state === 'before') t.textContent = 'Starts 1 October \u00B7 ' + C.bootcamp.time;
    else t.textContent = 'Bootcamp completed \u00B7 get access to the sessions';
  });
  $$('[data-bcdate]').forEach(function(el){ el.textContent = BC.state === 'live' ? 'Day ' + BC.idx + ' of ' + BC.total : (BC.state === 'done' ? 'Completed' : '1 to 21 Oct'); });
}
computeBC(); renderStatus();
